const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const C = require('../js/account-store.js');
const projectId = 'demo-morimens-account';
const empty = C.emptyRoster();

test('account Security Rules isolate users, validate envelopes and enforce deletion lock', async t => {
    const { initializeTestEnvironment, assertSucceeds, assertFails } = await import('@firebase/rules-unit-testing');
    const F = await import('firebase/firestore');
    assert.ok(process.env.FIRESTORE_EMULATOR_HOST, 'Emulator-only test');
    const env = await initializeTestEnvironment({ projectId, firestore: { rules: fs.readFileSync('firestore.account.rules', 'utf8') } });
    t.after(() => env.cleanup()); await env.clearFirestore();
    const a = env.authenticatedContext('alice').firestore(), b = env.authenticatedContext('bob').firestore(), guest = env.unauthenticatedContext().firestore();
    const profile = uid => F.doc(a, 'users', uid), record = (db, uid, kind = 'roster') => F.doc(db, 'users', uid, 'state', kind);
    const stamp = F.serverTimestamp;
    const makeProfile = () => ({ schemaVersion: 1, revision: 1, status: 'active', gameUid: null, createdAt: stamp(), updatedAt: stamp() });
    const makeState = (revision = 1, payload = C.encode(empty)) => ({ schemaVersion: 1, revision, updatedAt: stamp(), payloadJson: payload });
    await assertFails(F.setDoc(profile('bob'), makeProfile()));
    await assertFails(F.setDoc(record(a, 'alice'), makeState()));
    await assertSucceeds(F.setDoc(profile('alice'), makeProfile()));
    await assertSucceeds(F.setDoc(record(a, 'alice'), makeState()));
    await assertSucceeds(F.getDoc(record(a, 'alice')));
    await assertFails(F.getDoc(record(b, 'alice'))); await assertFails(F.getDoc(record(guest, 'alice')));
    await assertFails(F.getDocs(F.collection(a, 'users'))); await assertFails(F.getDocs(F.collection(a, 'users', 'alice', 'state')));
    await assertFails(F.setDoc(record(a, 'alice', 'arbitrary'), makeState()));
    await assertFails(F.setDoc(F.doc(a, 'releases', 'x'), makeState()));
    await assertFails(F.getDoc(F.doc(a, 'releases', 'x')));
    await assertFails(F.setDoc(record(a, 'alice'), makeState(1)));
    await assertFails(F.setDoc(record(a, 'alice'), { ...makeState(2), updatedAt: F.Timestamp.fromMillis(0) }));
    await assertFails(F.setDoc(record(a, 'alice'), makeState(2, 'x'.repeat(65537))));
    await assertFails(F.setDoc(record(a, 'alice'), makeState(2, '한글 원문')));
    await assertSucceeds(F.setDoc(record(a, 'alice'), makeState(2, C.encode({ ...empty, presets: [{ name: '한글', patch: {} }] }))));
    await assertFails(F.deleteDoc(record(a, 'alice')));
    await assertSucceeds(F.updateDoc(profile('alice'), { gameUid: '12345', revision: 2, updatedAt: stamp() }));
    await assertFails(F.updateDoc(profile('alice'), { gameUid: 'x'.repeat(65), revision: 3, updatedAt: stamp() }));
    await assertSucceeds(F.updateDoc(profile('alice'), { status: 'deleting', gameUid: null, revision: 3, updatedAt: stamp(), deleteRequestedAt: stamp() }));
    await assertFails(F.setDoc(record(a, 'alice'), makeState(3)));
    await assertSucceeds(F.deleteDoc(record(a, 'alice')));
    await assertFails(F.setDoc(record(a, 'alice'), makeState()));
    await assertFails(F.updateDoc(profile('alice'), { status: 'active', revision: 4, updatedAt: stamp() }));
    await assertFails(F.deleteDoc(profile('alice')));
});

test('real client driver uses Emulator Auth, merges two devices and deletes without resurrection', async t => {
    const A = await import('firebase/app'), H = await import('firebase/auth'), F = await import('firebase/firestore');
    assert.ok(process.env.FIREBASE_AUTH_EMULATOR_HOST); assert.ok(process.env.FIRESTORE_EMULATOR_HOST);
    const { createFirebaseDriver } = await import('../js/account-firebase.mjs');
    global.location = { hostname: 'localhost' };
    const driver = await createFirebaseDriver({ enabled: true, emulators: true, config: { apiKey: 'demo-key', projectId, authDomain: `${projectId}.firebaseapp.com`, appId: 'test-account' } }, [A, H, F]);
    const app = A.getApp('morimens-account'); t.after(() => A.deleteApp(app));
    const login = await driver.loginTest(`account-${Date.now()}@example.test`, 'local-test-password', true), uid = login.user.uid;
    const loaded = await driver.load(uid); assert.equal(loaded.profile.status, 'active'); assert.equal(loaded.roster, null);
    const initial = C.emptyRoster(); initial.characters.a = { owned: true, potency: 0, level: 1, talents: {}, skills: {} };
    await driver.save(uid, 'roster', null, initial);
    const other = C.clone(initial); other.wheels.w = { owned: true, potency: 3 }; await driver.save(uid, 'roster', initial, other);
    const mine = C.clone(initial); mine.characters.a.owned = false;
    const merged = await driver.save(uid, 'roster', initial, mine);
    assert.equal(merged.data.wheels.w.potency, 3); assert.equal(merged.data.characters.a.owned, false);
    const conflicting = C.clone(initial); conflicting.wheels.w = { owned: true, potency: 5 };
    const conflict = await driver.save(uid, 'roster', initial, conflicting); assert.ok(conflict.conflicts.length);
    const profile = await driver.updateProfile(uid, 'game-123'); assert.equal(profile.gameUid, 'game-123');
    await driver.deleteData(uid); await assert.rejects(driver.save(uid, 'roster', null, initial));
    const deleting = await driver.load(uid); assert.equal(deleting.profile.status, 'deleting');
    await driver.deleteIdentity(uid); assert.equal(H.getAuth(app).currentUser, null);
});

test('cleanup verifies Auth absence, preserves pending identities, and only deletes expired fixed paths', async t => {
    const { initializeApp, deleteApp } = await import('firebase-admin/app');
    const { getFirestore, Timestamp } = await import('firebase-admin/firestore');
    const { getAuth } = await import('firebase-admin/auth');
    const { cleanupAccounts } = await import('./account-cleanup.mjs');
    const app = initializeApp({ projectId }, 'account-cleanup-test'); t.after(() => deleteApp(app));
    const db = getFirestore(app), auth = getAuth(app), prefix = `cleanup-${Date.now()}`;
    const old = Timestamp.fromMillis(Date.now() - 48 * 3600000), cutoff = new Date(Date.now() - 24 * 3600000);
    const gone = db.doc(`users/${prefix}-gone`), retained = db.doc(`users/${prefix}-retained`);
    await auth.createUser({ uid: `${prefix}-retained` });
    await Promise.all([gone.set({ status: 'deleting', deleteRequestedAt: old }), retained.set({ status: 'deleting', deleteRequestedAt: old }), gone.collection('state').doc('roster').set({ payloadJson: '{}' })]);
    const dry = await cleanupAccounts({ db, auth, cutoff }); assert.ok(dry.eligible >= 1); assert.equal(dry.deleted, 0); assert.ok((await gone.get()).exists);
    const applied = await cleanupAccounts({ db, auth, cutoff, apply: true }); assert.ok(applied.deleted >= 1);
    assert.equal((await gone.get()).exists, false); assert.equal((await gone.collection('state').doc('roster').get()).exists, false); assert.equal((await retained.get()).exists, true);
    await auth.deleteUser(`${prefix}-retained`); await retained.delete();
});
