import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {ScarecrowEngine} from '../js/scarecrow/engine.mjs';
import {makeLiveDamageInput} from '../js/scarecrow/live-damage-input.mjs';
import {sequenceInput,sequenceStep} from '../js/scarecrow/sequence-calculator.mjs';

test('Native Lemuria → Strike keeps buffs, preview is repeatable, undo and reset restore baseline',async()=>{
 const read=async name=>JSON.parse(await readFile(new URL('../scarecrow/runtime/'+name,import.meta.url),'utf8'));
 const catalog=await read('catalog.json'),data=await read('live-data.json'),engine=new ScarecrowEngine();
 await engine.initialize(gunzipSync(await readFile(new URL('../scarecrow/runtime/engine.scpack.gz',import.meta.url))));
 const people=[15563,15564,15582,15589].map(id=>({...structuredClone(data.people.find(p=>p.id===id)),level:60,potency:0,sign:0,training:0,inherent:0,trinkets:[],gear1:'미장착',gear2:'미장착',contract:'미장착'}));
 const owner=people[0],lemuria=owner.cards.find(c=>c.id===4729),strike=owner.cards.find(c=>c.id===4714);
 const state={keeperId:0,crit:'비치명',weakness:2,power:0,stance:'조수',enemies:[{tid:72151,hp:100000,maxHp:100000}],customStates:[]};
 const call=(kind,value)=>engine.run(kind,value);
 const base=(await makeLiveDamageInput({catalog,call,state,people,person:owner,card:lemuria})).input;
 const first=sequenceStep(owner,lemuria,state),next=sequenceStep(owner,strike,state),history=[{step:first,replies:[]}];
 const started=performance.now();
 const applied=await call('calculator',sequenceInput(base,history,next));
 const team=applied.initial.roles.find(r=>r.roleType===3);
 assert.ok(!team.states.some(s=>s.stateId===3469&&s.layer>0),'Lemuria clears weakness');
 assert.ok(team.states.some(s=>s.layer>0&&s.stateId===3130),'temporary power remains');
 assert.ok(applied.steps.every(s=>s.accepted),'both cards use original legal commands');
 const repeated=await call('calculator',sequenceInput(base,history,next));
 assert.deepEqual(applied.current,repeated.current,'preview cannot consume the committed snapshot');
 const plain=(await makeLiveDamageInput({catalog,call,state,people,person:owner,card:strike})).input;
 const undone=await call('calculator',sequenceInput(plain,[],next));
 assert.ok(applied.damage.total>undone.damage.total,'Lemuria buffs increase Strike damage');
 assert.ok(undone.initial.roles.find(r=>r.roleType===3).states.some(s=>s.stateId===3469&&s.layer===2),'undo/reset restores weakness');
 const ally=people[1],allyStep=sequenceStep(ally,ally.cards[0],state);
 const allyResult=await call('calculator',sequenceInput(base,history,allyStep));
 assert.ok(allyResult.steps.every(s=>s.accepted),'another ally can use the preserved common buffs');
 assert.equal(allyResult.initial.roles.find(r=>r.roleType===3).states.find(s=>s.stateId===3130).layer,team.states.find(s=>s.stateId===3130).layer);
 const double=await call('calculator',sequenceInput(base,[...history,{step:first,replies:[]}],next));
 assert.ok(double.damage.total>applied.damage.total,'a second committed buff remains in the replay');
 const redo=await call('calculator',sequenceInput(base,history,next));assert.deepEqual(redo.current,applied.current,'undoing the second application returns to the first');
 const critical=await call('calculator',sequenceInput(base,history,{...next,critical:true}));
 assert.deepEqual(critical.initial.roles,applied.initial.roles,'preview critical mode cannot alter previously applied effects');
 assert.ok(critical.damage.hits.some(h=>h.critical),'the selected preview applies its own critical setting');
 const ultimate=owner.cards.find(c=>c.ulti),ultimateBase=(await makeLiveDamageInput({catalog,call,state,people,person:owner,card:ultimate})).input;
 const ultimateStep=sequenceStep(owner,ultimate,state),ult=await call('calculator',sequenceInput(ultimateBase,[],ultimateStep));
 assert.ok(ult.steps.every(s=>s.accepted),'first ultimate keeps the original automatic rage setup');
 const insufficient=await call('calculator',sequenceInput(ultimateBase,[],{...ultimateStep,rage:0}));
 assert.ok(insufficient.steps.some(s=>!s.accepted),'explicit insufficient rage cannot be bypassed');
 const twoEnemies={...state,enemies:[{tid:72151,hp:10000,maxHp:10000},{tid:149116,hp:10000,maxHp:10000}]};
 const twoBase=(await makeLiveDamageInput({catalog,call,state:twoEnemies,people,person:owner,card:strike})).input;
 const following=await call('calculator',sequenceInput(twoBase,[{step:next,replies:[]}],next));
 assert.ok(following.steps.every(s=>s.accepted));
 assert.ok(following.initial.roles.find(r=>r.camp===2).properties.hp<10000,'committed attacks preserve enemy HP loss');
 assert.ok(following.damage.total>0,'the next preview computes damage from the committed HP snapshot');
 const timing=[];for(const length of [0,1,5,20]){const start=performance.now();const result=await call('calculator',sequenceInput(length?base:plain,Array.from({length},()=>({step:first,replies:[]})),next));assert.ok(result.steps.every(s=>s.accepted));timing.push({applied:length,ms:Math.round(performance.now()-start)});}
 console.log(JSON.stringify({nativeWasmTiming:timing}));
 console.log(JSON.stringify({sequenceMs:Math.round(performance.now()-started),strike:undone.damage.total,afterLemuria:applied.damage.total,tentacle:applied.initial.tentacleDamage}));
});
